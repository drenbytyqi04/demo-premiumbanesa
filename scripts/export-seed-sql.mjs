// Write supabase/seed.sql from src/data/*.json (upsert, safe to re-run).
//   npm run export-seed
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = join(import.meta.dirname, '..')
const read = (f) => JSON.parse(readFileSync(join(ROOT, 'src', 'data', f), 'utf8'))
const complex = read('complex.json')
const buildings = read('buildings.json')
const apartments = read('apartments.json')

const q = (v) => (v === null || v === undefined ? 'null' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`)
const j = (v) => (v === null || v === undefined ? 'null' : `${q(JSON.stringify(v))}::jsonb`)
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`

const out = ['-- Generated by `npm run export-seed` from src/data/*.json. Safe to re-run (upsert).', 'begin;', '']
out.push(
  `insert into public.complex (id, name, tagline, location, aerial_image, aerial_width, aerial_height) values (1, ${q(complex.name)}, ${q(complex.tagline)}, ${q(complex.location)}, ${q(complex.aerial.image)}, ${complex.aerial.width}, ${complex.aerial.height})`,
  `  on conflict (id) do update set name = excluded.name, tagline = excluded.tagline, location = excluded.location, aerial_image = excluded.aerial_image, aerial_width = excluded.aerial_width, aerial_height = excluded.aerial_height;`,
  '',
)
buildings.forEach((b, i) => {
  out.push(
    `insert into public.buildings (id, name, description, floors, polygon, sort) values (${q(b.id)}, ${q(b.name)}, ${q(b.description)}, ${b.floors}, ${j(b.polygon)}, ${i})`,
    `  on conflict (id) do update set name = excluded.name, description = excluded.description, floors = excluded.floors, polygon = excluded.polygon, sort = excluded.sort;`,
  )
  b.facades.forEach((f, k) =>
    out.push(
      `insert into public.facades (id, building_id, label, image, width, height, sort) values (${q(f.id)}, ${q(b.id)}, ${q(f.label)}, ${q(f.image)}, ${f.width}, ${f.height}, ${k})`,
      `  on conflict (id) do update set building_id = excluded.building_id, label = excluded.label, image = excluded.image, width = excluded.width, height = excluded.height, sort = excluded.sort;`,
    ),
  )
})
out.push('')
for (const a of apartments)
  out.push(
    `insert into public.apartments (id, building_id, floor, number, area, rooms, price, status, facade_id, polygon, panorama_scene_ids, floor_plan) values (${[
      q(a.id), q(a.buildingId), a.floor, q(a.number), a.area, a.rooms, a.price, `${q(a.status)}::public.apartment_status`, q(a.facadeId), j(a.polygon), arr(a.panoramaSceneIds), q(a.floorPlan),
    ].join(', ')})`,
    `  on conflict (id) do update set building_id = excluded.building_id, floor = excluded.floor, number = excluded.number, area = excluded.area, rooms = excluded.rooms, price = excluded.price, status = excluded.status, facade_id = excluded.facade_id, polygon = excluded.polygon, panorama_scene_ids = excluded.panorama_scene_ids, floor_plan = excluded.floor_plan;`,
  )
out.push('', 'commit;', '')
writeFileSync(join(ROOT, 'supabase', 'seed.sql'), out.join('\n'))
console.log(`✔ supabase/seed.sql (${buildings.length} buildings, ${apartments.length} apartments)`)
